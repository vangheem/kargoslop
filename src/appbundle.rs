//! `~/Applications/kargoslop.app`: a small bundle, made on this Mac, that launches the installed
//! `kargoslop` binary. It's created locally rather than downloaded, so Gatekeeper never
//! quarantines it, and it points at Homebrew's version-independent `opt` path, so
//! `brew upgrade` updates the app without reinstalling it.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, anyhow};

/// Set by the bundle's launcher, so the app knows it was opened as an app.
pub const LAUNCHED_FROM_APP: &str = "KARGOSLOP_APP_BUNDLE";

const BUNDLE_ID: &str = "com.github.vangheem.kargoslop";
#[cfg(target_os = "macos")]
const ICNS: &[u8] = include_bytes!("../assets/kargoslop.icns");

pub fn supported() -> bool {
    cfg!(target_os = "macos")
}

pub fn app_path() -> PathBuf {
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .unwrap_or_default();
    home.join("Applications/kargoslop.app")
}

pub fn installed() -> bool {
    app_path().join("Contents/Info.plist").exists()
}

pub fn launched_from_app() -> bool {
    std::env::var_os(LAUNCHED_FROM_APP).is_some()
}

/// The binary the launcher should run: Homebrew's `opt` link when this one lives in its
/// Cellar (stable across upgrades), else this executable as it is.
pub fn target_binary() -> Result<PathBuf> {
    let exe = std::env::current_exe().context("find the kargoslop executable")?;
    let exe = exe.canonicalize().unwrap_or(exe);
    Ok(brew_opt_path(&exe).unwrap_or(exe))
}

/// `/opt/homebrew/Cellar/kargoslop/0.1.1/bin/kargoslop` → `/opt/homebrew/opt/kargoslop/bin/kargoslop`.
fn brew_opt_path(exe: &Path) -> Option<PathBuf> {
    let s = exe.to_str()?;
    let (prefix, rest) = s.split_once("/Cellar/kargoslop/")?;
    let (_version, tail) = rest.split_once('/')?;
    Some(PathBuf::from(format!("{prefix}/opt/kargoslop/{tail}")))
}

/// The launcher: picks up the login shell's PATH (apps opened from Finder get a bare one, and
/// kargoslop needs `kargo`, `argocd`, `kubectl` and its auth plugins), then becomes the real binary.
fn launcher(binary: &Path) -> String {
    let bin = binary.display().to_string().replace('\'', r"'\''");
    format!(
        r#"#!/bin/sh
# Generated by `kargoslop install-app`. Runs the installed kargoslop as an app.
login_path=$("${{SHELL:-/bin/zsh}}" -lc 'printf %s "$PATH"' 2>/dev/null)
export PATH="${{login_path:+$login_path:}}/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$PATH"
export {LAUNCHED_FROM_APP}=1
exec '{bin}' "$@"
"#
    )
}

fn info_plist(version: &str) -> String {
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>kargoslop</string>
  <key>CFBundleDisplayName</key><string>kargoslop</string>
  <key>CFBundleIdentifier</key><string>{BUNDLE_ID}</string>
  <key>CFBundleExecutable</key><string>kargoslop</string>
  <key>CFBundleIconFile</key><string>kargoslop</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>{version}</string>
  <key>CFBundleVersion</key><string>{version}</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
"#
    )
}

/// Creates (or refreshes) `~/Applications/kargoslop.app`, returning its path.
#[cfg(target_os = "macos")]
pub fn install() -> Result<PathBuf> {
    use std::os::unix::fs::PermissionsExt;

    let binary = target_binary()?;
    if !binary.exists() {
        return Err(anyhow!("{} doesn't exist", binary.display()));
    }
    let app = app_path();
    let contents = app.join("Contents");
    std::fs::create_dir_all(contents.join("MacOS"))?;
    std::fs::create_dir_all(contents.join("Resources"))?;
    std::fs::write(
        contents.join("Info.plist"),
        info_plist(env!("CARGO_PKG_VERSION")),
    )?;
    std::fs::write(contents.join("Resources/kargoslop.icns"), ICNS)?;
    let exe = contents.join("MacOS/kargoslop");
    std::fs::write(&exe, launcher(&binary))?;
    std::fs::set_permissions(&exe, std::fs::Permissions::from_mode(0o755))?;
    // Tell Launch Services (Spotlight, Launchpad, Finder) about it, and refresh its icon.
    let lsregister = "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister";
    let _ = std::process::Command::new(lsregister)
        .arg("-f")
        .arg(&app)
        .status();
    let _ = std::process::Command::new("touch").arg(&app).status();
    Ok(app)
}

#[cfg(not(target_os = "macos"))]
pub fn install() -> Result<PathBuf> {
    Err(anyhow!("kargoslop.app is only for macOS"))
}

pub fn uninstall() -> Result<bool> {
    let app = app_path();
    if !app.exists() {
        return Ok(false);
    }
    std::fs::remove_dir_all(&app).with_context(|| format!("remove {}", app.display()))?;
    Ok(true)
}

/// `kargoslop install-app` / `uninstall-app`. Returns false for anything else, so the app runs.
pub fn cli(args: &[String]) -> bool {
    let result = match args.get(1).map(String::as_str) {
        Some("install-app") => install().map(|app| {
            println!("Installed {}", app.display());
            println!("Open kargoslop from Spotlight, Launchpad or Finder. `brew upgrade` keeps it current.");
        }),
        Some("uninstall-app") => uninstall().map(|removed| {
            if removed {
                println!("Removed {}", app_path().display());
            } else {
                println!("{} isn't installed", app_path().display());
            }
        }),
        _ => return false,
    };
    if let Err(e) = result {
        eprintln!("kargoslop: {e:#}");
        std::process::exit(1);
    }
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn homebrew_cellar_paths_become_opt_paths() {
        let p = brew_opt_path(Path::new(
            "/opt/homebrew/Cellar/kargoslop/0.1.1/bin/kargoslop",
        ));
        assert_eq!(
            p,
            Some(PathBuf::from("/opt/homebrew/opt/kargoslop/bin/kargoslop"))
        );
        assert_eq!(
            brew_opt_path(Path::new("/Users/me/.local/bin/kargoslop")),
            None
        );
    }
}
